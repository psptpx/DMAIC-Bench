DATA = Path("output/research/results-summary-20260924.json")
PROPOSALS = Path("output/figure_proposals/results-summary-13-models")
PROPOSALS.mkdir(parents=True, exist_ok=True)
OUT = PROPOSALS / "figure04_results_summary"


def require_input(path, producer):
    """Exit with a plain message when a run-artifact input is absent from the checkout."""
    if not Path(path).exists():
        sys.exit(f"missing input {path}: this file is not part of the tracked tree. It comes from "
                 f"the run-artifact archive ({producer}); see scripts/README.md, Analysis inputs.")
STYLES = {
    "GPT-6-astra": ("#237E78", "^"), "GPT-5.6-sol": ("#52A39B", "^"),
    "GPT-5.6-luna": ("#8BBDB5", "^"), "Claude-Fable-5.1": ("#D08B69", "o"),
    "Claude-Opus-5": ("#DFAF94", "o"), "Claude-Sonnet-5": ("#B96944", "o"),
    "DeepSeek-v4-flash": ("#5267AE", "D"), "DeepSeek-v4-pro": ("#919ED0", "D"),
    "GLM-5.3": ("#BC426B", "+"), "GLM-5.3-Flash": ("#D47798", "+"),
    "Kimi-k3": ("#9A66AA", "v"), "Qwen3.8-max": ("#796394", "s"),
    "Qwen3.8-flash": ("#AB95C0", "s"),
}


def collect():
    rank = json.loads(Path("docs/result_restraint.json").read_text())
    result = {"criterion": "pq.score == 1 with points_total > 0",
              "attempt_order": "SYSTEMS job order, sorted trial directories; first three per task",
              "models": {}, "sources_sha256": {}}
    shapes = CR._shape_lookup()
    for name, vendor, first, extra in RA.SYSTEMS:
        by = defaultdict(list)
        rows = []
        for job in first + extra:
            folder = RA.JOBS / job
            if not folder.exists():
                continue
            for row in CR._rows(folder):
                if row["agent"] in ("oracle", "nop"):
                    continue
                card = folder / row["trial"] / "verifier-rescored/scorecard.json"
                if not card.exists():
                    card = folder / row["trial"] / "verifier/scorecard.json"
                row["source"] = str(card)
                by[row["task_id"]].append(row)
                rows.append(row)
        assert len(by) == 97 and min(map(len, by.values())) >= 3, name
        assert set(by) == {r["task_id"] for r in RA.load_rows(first)}, name
        tasks = {}
        for tid, attempts in sorted(by.items()):
            selected = attempts[:3]
            tasks[tid] = {"success": [CR._all_decisions_right(r) for r in selected],
                          "tier": CR._tier(selected[0], shapes),
                          "sources": [r["source"] for r in selected]}
            for r in selected:
                p = r["source"]
                result["sources_sha256"][p] = hashlib.sha256(Path(p).read_bytes()).hexdigest()
        curves = {"any": [], "all": []}
        for k in (1, 2, 3):
            curves["any"].append(sum(any(t["success"][:k]) for t in tasks.values()))
            curves["all"].append(sum(all(t["success"][:k]) for t in tasks.values()))
        # Cross-check the saved tier table's analysis, without rounding the plot inputs.
        tiers = CR.passk(rows, shapes, 3)["by_tier"]
        for tier in tiers:
            subset = [t for t in tasks.values() if t["tier"] == tier]
            assert round(sum(all(t["success"]) for t in subset) / len(subset), 4) == tiers[tier]["passk_decisions"]
        result["models"][name] = {"n_tasks": 97, "curves_counts": curves,
                                  "attempt_summary": rank[name]["att"], "tasks": tasks}
    DATA.write_text(json.dumps(result, indent=2) + "\n")
    return rank, result


def table(rank):
    lines = [r"% Generated by scripts/fig_results_summary.py from docs/result_restraint.json.",
             r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}rlrrrrr@{}}",
             r"\toprule",
             r"Rank & Agent & \thead{Mean\\reward $\uparrow$} & \thead{NO-GO\\right (\%)} & \thead{GO\\right (\%)} & \thead{Both sides\\(of 40)} & \thead{B-divert\\(of 18)} \\",
             r"\midrule",
             r"--- & Reference solution$^\dagger$ & 1.000 & 100 & 100 & 40 & 18 \\",
             r"\midrule"]
    for i, (name, r) in enumerate(sorted(rank.items(), key=lambda x: -x[1]["mean"]), 1):
        nn, nw, gn, gw, both, forks = r["matched"]
        assert (nn, gn, forks) == (52, 146, 40)
        lines.append(f"{i} & {RA.logo(r['vendor'])} {name} & {r['mean']:.3f} & "
                     f"{100*(nn-nw)/nn:.0f} & {100*(gn-gw)/gn:.0f} & {both} & {r['bdiv'][0]} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    (PROPOSALS / "tab_main_results.tex").write_text("\n".join(lines) + "\n")


def permission_table(rank):
    # Reuse the frozen decision-class ledger, rather than regenerate private truth.
    ledger_path = Path("output/research/appendix_diagnostics/decision_outcomes.csv")
    require_input(ledger_path, "written by scripts/fig_appendix_diagnostics.py from the retained harbor/jobs trials")
    kinds = {}
    for row in csv.DictReader(ledger_path.open()):
        key = row["task"], row["point"]
        assert kinds.get(key, row["kind"]) == row["kind"]
        kinds[key] = row["kind"]
    assert len(kinds) == 300
    summary = {}; shapes = CR._shape_lookup()
    for label, vendor, jobs, _ in RA.CONTROLS:
        name = label.removesuffix(" [permit-stop]")
        rows = RA.load_rows(jobs)
        assert len(rows) == 97
        totals = defaultdict(list); forks = defaultdict(lambda: defaultdict(list))
        bdiv = 0
        for row in rows:
            for point in row["card"]["scorecard"]["pq"]["details"]:
                if point.get("kind") != "decision_point":
                    continue
                kind = kinds[row["task_id"], point["point_id"]]
                correct = point["verdict"] == "correct"
                totals[kind].append(correct)
                forks[row["case_id"], point["point_id"]][kind].append(correct)
            if CR._tier(row, shapes) == "B-divert":
                bdiv += CR._all_decisions_right(row)
        matched = [f for f in forks.values() if f["NO-GO"] and f["GO"]]
        assert len(matched) == 40
        assert [len(totals[k]) for k in ["NO-GO", "GO"]] == [52, 248]
        summary[name] = {k: sum(totals[k])/len(totals[k])*100 for k in ("NO-GO", "GO")}
        summary[name].update(both=sum(all(f["NO-GO"]+f["GO"]) for f in matched), bdiv=bdiv)
    lines = [r"% Generated from retained first-attempt scorecards by scripts/fig_results_summary.py.",
             r"{\small\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrrr@{}}",
             r"\toprule",
             r"Agent & \thead{NO-GO right\\(\%)} & \thead{GO right\\(\%)} & \thead{Both sides\\(of 40)} & \thead{B-divert\\(of 18)} \\",
             r"\midrule"]
    for name, baseline in sorted(rank.items(), key=lambda x:-x[1]["mean"]):
        r = summary[name]
        cells = [f"{RA.logo(baseline['vendor'])} {name}"]
        for k in ("NO-GO", "GO"):
            old = (1-baseline[k]["wrong"]/baseline[k]["n"])*100
            cells.append(f"{old:.0f} $\\rightarrow$ {r[k]:.0f}")
        cells += [f"{baseline['matched'][4]} $\\rightarrow$ {r['both']}",
                  f"{baseline['bdiv'][0]} $\\rightarrow$ {r['bdiv']}"]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular*}}"]
    (PROPOSALS / "tab_control.tex").write_text("\n".join(lines)+"\n")
    audit = {"models": summary, "below_50_nogo": sum(r["NO-GO"] < 50 for r in summary.values()),
             "decision_ledger_sha256": hashlib.sha256(ledger_path.read_bytes()).hexdigest()}
    Path("output/research/permission-summary-20260924.json").write_text(json.dumps(audit, indent=2)+"\n")


def plot(data):
    plt.rcParams.update({"font.family": "sans-serif", "font.sans-serif": ["Helvetica", "Arial", "DejaVu Sans"],
                         "font.size": 7, "axes.labelsize": 7, "xtick.labelsize": 6.5,
                         "ytick.labelsize": 6.5, "pdf.fonttype": 42, "svg.fonttype": "none",
                         "axes.spines.top": False, "axes.spines.right": False,
                         "text.color": "#34414B", "axes.labelcolor": "#34414B"})
    fig = plt.figure(figsize=(396/72, 174/72))
    a = fig.add_axes([.075, .18, .30, .61])
    b = fig.add_axes([.48, .18, .28, .61])
    for ax in (a, b):
        ax.grid(axis="y", color="#E8EDF1", lw=.6)
        ax.set_axisbelow(True)
        ax.tick_params(colors="#697988", length=2.5, pad=2)
        for spine in ax.spines.values():
            spine.set_color("#8C9AA7"); spine.set_linewidth(.6)
    fig.text(.075, .93, "(a)  Reward and restraint", weight="bold", color="#125DA1", size=7.5)
    fig.text(.075, .845, "13 models · mean ± SD", color="#596570", size=6.5)
    fig.text(.48, .93, "(b)  Repeated-attempt reliability", weight="bold", color="#125DA1", size=7.5)
    fig.text(.48, .845, "13 models · 97 shared tasks", color="#596570", size=6.5)
    xs = [m["attempt_summary"]["mean"] for m in data["models"].values()]
    ys = [m["attempt_summary"]["nogo"] for m in data["models"].values()]
    a.axvline(np.median(xs), color="#A3AFBA", ls=(0, (3, 3)), lw=.7)
    a.axhline(np.median(ys), color="#A3AFBA", ls=(0, (3, 3)), lw=.7)
    for name, (color, marker) in STYLES.items():
        m = data["models"][name]; s = m["attempt_summary"]
        a.errorbar(s["mean"], s["nogo"], xerr=s["mean_sd"], yerr=s["nogo_sd"],
                   fmt="none", ecolor=color, alpha=.35, elinewidth=.6, capsize=1.4)
        a.plot(s["mean"], s["nogo"], marker=marker, color=color, ms=3.3, mew=.6, ls="none")
        for metric, style in (("any", (0, (1, 2.5))), ("all", "-")):
            b.plot([1, 2, 3], np.array(m["curves_counts"][metric])*100/97,
                   color=color, marker=marker, ms=2.8, mew=.6, lw=.8, ls=style)
    for name, offset, align in [("GPT-6-astra", (-3, 8), "right"),
                                ("GPT-5.6-luna", (-3, 9), "right"),
                                ("Qwen3.8-max", (3, 6), "left"),
                                ("Qwen3.8-flash", (3, -9), "left")]:
        s = data["models"][name]["attempt_summary"]
        a.annotate(name, (s["mean"], s["nogo"]), xytext=offset,
                   textcoords="offset points", ha=align, size=6)
    a.set(xlim=(.35, .705), ylim=(0, 33), xticks=[.35, .45, .55, .65], yticks=[0, 10, 20, 30],
          xlabel="Mean reward", ylabel="NO-GO accuracy (%)")
    b.set(xlim=(.88, 3.12), ylim=(0, 42), xticks=[1, 2, 3], yticks=[0, 10, 20, 30, 40],
          xlabel="Attempts, $k$", ylabel="All-decision success (%)")
    b.legend([Line2D([], [], color="#34414B", ls=(0, (1, 2.5)), lw=.9),
              Line2D([], [], color="#34414B", ls="-", lw=.9)],
             [r"pass@$k$: any succeed", r"pass$^k$: all succeed"], loc="lower left",
             frameon=False, fontsize=6, handlelength=1.5, handletextpad=.5, borderpad=0,
             labelspacing=.25)
    handles = [Line2D([], [], color=c, marker=m, ls="none", markersize=3, label=n)
               for n, (c, m) in STYLES.items()]
    fig.legend(handles=handles, loc="upper left", bbox_to_anchor=(.785, .82),
               frameon=False, fontsize=6.4, borderpad=0, handletextpad=.35,
               handlelength=.8, labelspacing=.32)
    for ext in ("pdf", "svg"):
        fig.savefig(OUT.with_suffix("." + ext), dpi=300)
    svg = OUT.with_suffix(".svg")
    svg.write_text("\n".join(line.rstrip() for line in svg.read_text().splitlines()) + "\n")
    plt.close(fig)
    with fitz.open(OUT.with_suffix(".pdf")) as pdf:
        pdf[0].get_pixmap(dpi=240).save(OUT.with_suffix(".png"))


if __name__ == "__main__":
    require_input(RA.JOBS, "the retained harbor/jobs trial directories, shipped as the results archive")
    rank, data = collect()
    table(rank)
    permission_table(rank)
    plot(data)
    for name, m in data["models"].items():
        print(name, m["curves_counts"])
