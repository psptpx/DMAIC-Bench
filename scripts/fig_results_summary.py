#!/usr/bin/env python3
"""Generate a Figure 4 proposal and comparison tables from retained results.

Run from the repository root. Reliability uses the same first-three retained-job
ordering and all-decisions-right criterion as campaign_report.passk. No rescoring
or new agent runs are performed. Exact task outcomes and source hashes are saved.
Accepted manuscript figures and tables are never overwritten by this script.
"""
