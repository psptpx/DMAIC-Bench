#!/usr/bin/env python3
"""Where can the steward lock a precondition, and where can it only watch?

    PYTHONPATH=.:harbor/src python3 scripts/lockability.py

For every graded no-go fork in the corpus (a (case, node) with at least one no-go seed), the
guard's atoms are classed by precondition type; a type is *publicly gated* if its atom maps to a
steward gate (_ATOM_TO_GATE), and a fork is *cross-batch* if the batch it would gate is not the
batch the guard is computed from. A fork is locked only if both hold (v2_tasks.locks). Writes
paper/iclr/tab_locks.tex and paper/iclr/locks.tex.
"""
import re, sys
from collections import defaultdict
from pathlib import Path
sys.path[:0] = [".", "harbor/src", "scripts"]
import restraint_analysis as RA
from dmaic_harbor import v2_tasks as V

OUT = Path("paper/iclr")
TYPE = [("gauge study (%SV, %tol)", ("pctsv", "pcttol"), "msa_pass"),
        ("distinct categories (ndc)", ("ndc",), "msa_ndc"),
        ("attribute agreement ($\\kappa$)", ("kappamin",), None),
        ("statistical control", ("outofcontrol", "rangeoutofcontrol", "soutofcontrol", "varyingn"), "stability_pass"),
        ("normality", ("pvalue",), "normality_pass"),
        ("screening significance", ("modelpvalue", "factorpvalue"), "screening_significant"),
        ("capability against target", ("ppk", "cpk", "cp", "avgp", "centerline"), None),
        ("confirmation / fit", ("lackoffitpvalue", "predictedresponse", "pointsize", "topcategorypct"), None)]


def atom_type(a):
    for label, atoms, gate in TYPE:
        if a in atoms:
            return label, gate
    return "other", None


def main():
    cases = RA.V.discover()
    rows = RA.load_rows(["gpt6astra-97"])          # one full campaign gives every (task, fork)
    forks = defaultdict(lambda: {"nogo_tasks": 0, "go_tasks": 0, "gate": None, "cross": False, "locked": False, "cases": set()})
    for r, p, _v, _o, _s, _d in RA.decisions(rows, cases):
        c = cases[r["case_id"]]; key = (r["case_id"], p["point_id"])
        f = forks[key]; f["cases"].add(r["case_id"])
        if RA.is_stop(p): f["nogo_tasks"] += 1
        else: f["go_tasks"] += 1
        if f["gate"] is None:
            atoms = set()
            for e in c.graph.edges_from(p["point_id"]):
                for a in RA._FIELD_RE.findall(e.when or ""):
                    if not a[0].isdigit(): atoms.add(a.split(".")[-1].lower())
            types = {atom_type(a) for a in atoms}
            f["types"] = types
            f["gate"] = any(g for _t, g in types)
            blocks = V.data_nodes(c)
            src_block = blocks.get(p["point_id"])
            targets = [e.target for e in c.graph.edges_from(p["point_id"])]
            f["cross"] = any(blocks.get(t) not in (None, src_block) for t in targets)
            lk = V.locks(c)
            own = {g for _t, g in types if g}
            f["locked"] = any(own & set(lk.get(blocks.get(t), {}).get("gates") or []) for t in targets)
    per = defaultdict(lambda: {"forks": 0, "nogo": 0, "gate": None, "cross": 0, "locked": 0})
    for key, f in forks.items():
        if f["nogo_tasks"] == 0: continue
        for label, gate in f["types"]:
            d = per[label]; d["forks"] += 1; d["nogo"] += f["nogo_tasks"]; d["gate"] = gate is not None
            d["cross"] += f["cross"]; d["locked"] += f["locked"]
    order = [t[0] for t in TYPE] + ["other"]
    L = ["\\begin{tabular}{@{}lrrlrr@{}}", "\\toprule",
         '\\thead{Precondition} & \\multicolumn{1}{c}{\\thead{No-go\\\\forks}} & \\multicolumn{1}{c}{\\thead{No-go\\\\decisions}} & \\thead{Public\\\\gate} & \\multicolumn{1}{c}{\\thead{Cross-batch\\\\forks}} & \\multicolumn{1}{c}{\\thead{Locked\\\\forks}} \\\\', "\\midrule"]
    tot = defaultdict(int)
    for label in order:
        if label not in per: continue
        d = per[label]
        tex_label = label.replace("%", r"\%")
        L.append(f"{tex_label} & {d['forks']} & {d['nogo']} & {'yes' if d['gate'] else 'no'} & {d['cross']} & {d['locked']} \\\\")
        for k in ("forks", "nogo", "cross", "locked"): tot[k] += d[k]
    L += ["\\midrule", f"Total & {tot['forks']} & {tot['nogo']} & & {tot['cross']} & {tot['locked']} \\\\", "\\bottomrule", "\\end{tabular}"]
    (OUT / "tab_locks.tex").write_text("\n".join(L) + "\n")
    (OUT / "locks.tex").write_text("% generated by scripts/lockability.py\n"
        + f"\\newcommand{{\\lkForks}}{{{tot['forks']}}}\n\\newcommand{{\\lkNogoTasks}}{{{tot['nogo']}}}\n"
        + f"\\newcommand{{\\lkCross}}{{{tot['cross']}}}\n\\newcommand{{\\lkLocked}}{{{tot['locked']}}}\n"
        + f"\\newcommand{{\\lkNoGateTypes}}{{{sum(1 for l in order if l in per and not per[l]['gate'])}}}\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
