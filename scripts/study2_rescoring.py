#!/usr/bin/env python3
"""Rescore the study-2 audit sample under three assessment criteria.

Reads paper/blind_review_2026-09-19/coordinator/results_study2.json (frozen expert
labels, one record per audited unit) and prints, for NO-GO (population-weighted) and
GO (unweighted) units, the rate under

  route         the benchmark's route verdict (forbidden computation is an error)
  rescored      route, plus credit for route errors whose forbidden computation the
                experts judged withheld or replaced by a valid alternative (NO-GO), or
                whose conduct the experts judged acceptable (GO)
  semantic      the experts' decision-correctness label (gate majority and no forbidden
                conclusion or action for NO-GO; gate majority and no warranted
                conclusion withheld for GO)

and the GO minus NO-GO difference, each with a case-clustered bootstrap interval
(12 sampled cases, 4000 draws, fixed seed). Writes paper/iclr/tab_study2rules.tex.
"""
import json, random, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "paper/blind_review_2026-09-19/coordinator/results_study2.json"
OUT = ROOT / "paper/iclr/tab_study2rules.tex"
RULES = ("route", "rescored", "semantic")


def verdicts(u):
    route = u["scorer"] == "correct"
    if u["kind"] == "STOP":
        return {"route": route, "rescored": route or not u["acted"],
                "semantic": u["gate_verdict"] == "STOP" and not u["acted"]}
    return {"route": route, "rescored": route or u["trajectory_verdict"] == "ACCEPTABLE",
            "semantic": u["gate_verdict"] == "GO" and u["report_withholds_warranted_conclusion"] != "YES"}


def rate(units, rule, weighted):
    num = den = 0.0
    for u in units:
        w = u["weight"] if weighted else 1.0
        num += w * verdicts(u)[rule]
        den += w
    return num / den


def main(seed=20260925, draws=4000):
    units = json.loads(SRC.read_text())["units"]
    stop = [u for u in units if u["kind"] == "STOP"]
    go = [u for u in units if u["kind"] == "GO"]
    cases = sorted({u["case"] for u in units})
    by_case = {c: [u for u in units if u["case"] == c] for c in cases}
    rng = random.Random(seed)
    boot = {r: [] for r in RULES}
    for _ in range(draws):
        samp = [u for c in rng.choices(cases, k=len(cases)) for u in by_case[c]]
        s = [u for u in samp if u["kind"] == "STOP"]
        g = [u for u in samp if u["kind"] == "GO"]
        if not s or not g:
            continue
        for r in RULES:
            boot[r].append((rate(s, r, True), rate(g, r, False)))

    def ci(xs):
        xs = sorted(xs)
        return xs[int(0.025 * len(xs))], xs[int(0.975 * len(xs)) - 1]

    rows = []
    for r in RULES:
        ns, ng = rate(stop, r, True), rate(go, r, False)
        lo, hi = ci([a for a, b in boot[r]])
        glo, ghi = ci([b for a, b in boot[r]])
        dlo, dhi = ci([b - a for a, b in boot[r]])
        ks = sum(verdicts(u)[r] for u in stop)
        kg = sum(verdicts(u)[r] for u in go)
        rows.append((r, ns, lo, hi, ks, ng, glo, ghi, kg, ng - ns, dlo, dhi))
        print(f"{r:9s} NO-GO {ns*100:3.0f}% [{lo*100:.0f}-{hi*100:.0f}] ({ks}/{len(stop)} unweighted)  "
              f"GO {ng*100:3.0f}% [{glo*100:.0f}-{ghi*100:.0f}] ({kg}/{len(go)})  "
              f"diff {(ng-ns)*100:3.0f} [{dlo*100:.0f}, {dhi*100:.0f}]")
    models = sorted({u["model"] for u in units})
    print(f"units {len(units)}, cases {len(cases)}, agents {len(models)}")
    label = {"route": "Route (forbidden computation is an error)",
             "rescored": "Route, crediting expert-confirmed withheld or alternative computations (rescoring)",
             "semantic": "Expert decision correctness"}
    tex = ["% generated by scripts/study2_rescoring.py -- do not edit",
           "\\begin{table}[!ht]",
           "\\caption{\\textbf{Execution and expert-assessed outcomes on the Study~2 sample.} "
           f"The same {len(stop)} NO-GO and {len(go)} GO units under three assessment criteria, which are distinct judgements rather than thresholds of one score. "
           "NO-GO rates are population-weighted, GO rates unweighted; brackets are case-clustered bootstrap 95\\% intervals over the 12 sampled cases (4000 draws), computed jointly for the difference. "
           "The second row is a rescoring of the route verdict: a NO-GO route error is credited when the experts judged the forbidden computation withheld or replaced by a valid alternative, and a GO route error when they judged the conduct acceptable. "
           f"Units come from {len(models)} of the 13 evaluated agents. A count in place of a rate marks a boundary rate whose bootstrap interval is degenerate (Appendix~\\ref{{app:ranking}}). The intervals come from a bootstrap run separate from Table~\\ref{{tab:study2}} and can differ from it by a point.}}",
           "\\label{tab:study2rules}", "\\centering\\small", "\\setlength{\\tabcolsep}{4pt}",
           "\\begin{tabular}{p{5.6cm}ccc}", "\\toprule",
           "Assessment criterion & NO-GO correct & GO correct & GO $-$ NO-GO \\\\", "\\midrule"]
    for r, ns, lo, hi, ks, ng, glo, ghi, kg, dd, dlo, dhi in rows:
        gcell = f"{kg}/{len(go)}" if glo == ghi else f"{ng*100:.0f}\\% [{glo*100:.0f}--{ghi*100:.0f}]"
        tex.append(f"{label[r]} & {ns*100:.0f}\\% [{lo*100:.0f}--{hi*100:.0f}] & {gcell} & {dd*100:.0f} [{dlo*100:.0f}--{dhi*100:.0f}] \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT.write_text("\n".join(tex))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
