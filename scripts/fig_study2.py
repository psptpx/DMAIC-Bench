#!/usr/bin/env python3
"""Figure 5: route accuracy, expert-semantic accuracy, and report violations.

    python3 scripts/fig_study2.py

All estimates use the retained study-2 units. NO-GO uses the frozen sampling
weights; GO is unweighted. The case bootstrap matches coordinator/synthesize.py.
One panel compares three separate measures, never a partition of overlapping
events. The panel shares its physical canvas and 7 pt type with Figure 6.
"""
import argparse
import json
from pathlib import Path
import random

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.transforms import blended_transform_factory
from figure_pair_style import (
    FIGURE_SIZE, FONT_SIZE, AXES_BOTTOM, AXES_HEIGHT, LEGEND_TOP, FOOTER_Y,
    apply_style, direction_arrow,
)


ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "paper/blind_review_2026-09-19/coordinator/results_study2.json"
NO_GO = "#B85E21"
GO = "#0072B2"
INK = "#202830"


def estimate(rows, predicate, weighted, draws=4000, seed=20260919):
    """Use the original case-clustered percentile bootstrap and fixed seed."""
    def rate(sample):
        weights = [r["weight"] if weighted else 1.0 for r in sample]
        return sum(w for r, w in zip(sample, weights) if predicate(r)) / sum(weights)

    rng = random.Random(seed)
    cases = sorted({r["case"] for r in rows})
    by_case = {case: [r for r in rows if r["case"] == case] for case in cases}
    values = []
    for _ in range(draws):
        sample = [r for case in rng.choices(cases, k=len(cases)) for r in by_case[case]]
        values.append(rate(sample))
    values.sort()
    return {
        "rate": rate(rows),
        "n": len(rows),
        "k": sum(bool(predicate(r)) for r in rows),
        "ci95_case_clustered": [
            round(values[int(0.025 * draws)], 3),
            round(values[int(0.975 * draws) - 1], 3),
        ],
        "weighted": weighted,
    }


def figure_data(data):
    result = {}
    for kind, key in (("STOP", "no_go"), ("GO", "go")):
        rows = [r for r in data["units"] if r["kind"] == kind]
        weighted = kind == "STOP"
        semantic = (
            (lambda r: r["gate_verdict"] == "STOP" and not r["acted"])
            if weighted else
            (lambda r: r["gate_verdict"] == "GO"
             and r["report_withholds_warranted_conclusion"] != "YES")
        )
        result[key] = {
            "route": estimate(rows, lambda r: r["scorer"] == "correct", weighted),
            "semantic": estimate(rows, semantic, weighted),
            "violations": estimate(rows, lambda r: r["acted"], weighted),
        }
        stored_semantic = data["expert_semantic_correct"]["stop" if weighted else "go"]
        stored_violations = data["stop_all_40" if weighted else "go_twins_20"]["acted_on_invalid_evidence"]
        for metric, stored in (("semantic", stored_semantic), ("violations", stored_violations)):
            actual = result[key][metric]
            assert round(actual["rate"], 3) == stored["rate"], (key, metric, "rate")
            assert actual["ci95_case_clustered"] == stored["ci95_case_clustered"], (key, metric, "CI")
            assert (actual["n"], actual["k"]) == (stored["n"], stored["k"]), (key, metric, "count")
    return result


def route_macros(data):
    lines = ["% Generated by scripts/fig_study2.py from the study-2 units."]
    for group, macro in (("no_go", "Stop"), ("go", "Go")):
        item = data[group]["route"]
        lo, hi = item["ci95_case_clustered"]
        lines.extend([
            rf"\newcommand{{\sTwoRoute{macro}Right}}{{{item['rate'] * 100:.0f}}}",
            rf"\newcommand{{\sTwoRoute{macro}RightCI}}{{{lo * 100:.0f}--{hi * 100:.0f}}}",
        ])
    return "\n".join(lines) + "\n"


def draw(data):
    apply_style()
    fig = plt.figure(figsize=FIGURE_SIZE)
    ax = fig.add_axes([0.34, AXES_BOTTOM, 0.605, AXES_HEIGHT])
    ax.set_xlim(0, 100)
    ax.set_ylim(-0.46, 2.46)
    ax.set_xticks([0, 25, 50, 75, 100], ["0%", "25%", "50%", "75%", "100%"])
    ax.set_yticks([])
    # Labels share a left edge; arrows occupy their own aligned column.
    label_transform = blended_transform_factory(fig.transFigure, ax.transData)
    for y, label, upward in (
        (2, "Route\naccuracy", True),
        (1, "Expert-rated\naccuracy", True),
        (0, "Report\nviolations", False),
    ):
        ax.text(0.045, y, label, transform=label_transform,
                ha="left", va="center", multialignment="left",
                fontsize=FONT_SIZE, linespacing=1.18)
        arrow_y = AXES_BOTTOM + AXES_HEIGHT * (y + 0.46) / 2.92
        direction_arrow(fig, 0.293, arrow_y, upward=upward)
    ax.tick_params(axis="x", labelsize=FONT_SIZE, length=2, pad=2.5, width=0.45)
    ax.xaxis.grid(True, color="#E8EDF1", linewidth=0.4)
    ax.set_axisbelow(True)
    for side in ("left", "right", "top"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color("#AFBAC3")
    ax.spines["bottom"].set_linewidth(0.45)
    for y in (1.5, 0.5):
        ax.axhline(y, color="#E8EDF1", linewidth=0.4, zorder=0)

    fig.legend(handles=[
        Line2D([], [], color=NO_GO, marker="s", markerfacecolor="white",
               linewidth=0.65, markeredgewidth=0.65, markersize=3.1,
               label=f"NO-GO (n={data['no_go']['route']['n']})"),
        Line2D([], [], color=GO, marker="o", linewidth=0.65,
               markeredgewidth=0.65, markersize=3.1,
               label=f"GO (n={data['go']['route']['n']})"),
    ], loc="upper center", bbox_to_anchor=(0.5, LEGEND_TOP), ncol=2, frameon=False,
        fontsize=FONT_SIZE, handlelength=1.2, handletextpad=0.5, columnspacing=1.2,
        borderaxespad=0)

    def point(item, y, color, marker, label_offset):
        value = item["rate"] * 100
        low, high = [v * 100 for v in item["ci95_case_clustered"]]
        ax.errorbar(value, y, xerr=[[value - low], [high - value]],
                    fmt=marker, markersize=3.1, color=color,
                    markerfacecolor="white" if marker == "s" else color,
                    markeredgewidth=0.65, elinewidth=0.65,
                    capsize=1.65, capthick=0.6, zorder=3)
        ax.annotate(f"{value:.0f}%", (value, y), xytext=(0, label_offset),
                    textcoords="offset points", ha="center",
                    va="bottom" if label_offset > 0 else "top",
                    fontsize=FONT_SIZE, fontweight="normal", color=color)

    for metric, y in (("route", 2), ("semantic", 1), ("violations", 0)):
        point(data["no_go"][metric], y + 0.14, NO_GO, "s", 3)
        point(data["go"][metric], y - 0.14, GO, "o", -3)

    # Use the same face/size as the axes; arrows are vectors, not fallback glyphs.
    direction_arrow(fig, 0.155, FOOTER_Y, upward=True)
    fig.text(0.185, FOOTER_Y, "Higher is better", ha="left", va="center",
             fontsize=FONT_SIZE, color="#596570")
    direction_arrow(fig, 0.57, FOOTER_Y, upward=False)
    fig.text(0.60, FOOTER_Y, "Lower is better", ha="left", va="center",
             fontsize=FONT_SIZE, color="#596570")
    return fig


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--figure-dir", type=Path, default=ROOT / "paper/iclr/figure_archive/generated")
    parser.add_argument("--metrics-out", type=Path, default=ROOT / "paper/iclr/study2_route_metrics.tex")
    parser.add_argument("--audit-out", type=Path, default=ROOT / "output/research/figure5_plot_data.json")
    args = parser.parse_args()
    data = figure_data(json.loads(SRC.read_text()))
    fig = draw(data)
    args.figure_dir.mkdir(parents=True, exist_ok=True)
    for extension in ("pdf", "png", "svg"):
        fig.savefig(args.figure_dir / f"figure4_study2.{extension}", dpi=300)
    plt.close(fig)
    args.metrics_out.parent.mkdir(parents=True, exist_ok=True)
    args.metrics_out.write_text(route_macros(data))
    args.audit_out.parent.mkdir(parents=True, exist_ok=True)
    args.audit_out.write_text(json.dumps({
        "source": str(SRC.relative_to(ROOT)),
        "bootstrap_draws": 4000,
        "bootstrap_seed": 20260919,
        "panels": data,
    }, indent=2) + "\n")
    print(json.dumps(data, indent=2))


if __name__ == "__main__":
    main()
