#!/usr/bin/env python3
"""How many fork verdicts the fork-scoped evidence rule changes, on the retained baseline trials.

    PYTHONPATH=.:harbor/src python3 scripts/pq_scoping_delta.py [--tex paper/iclr/scoping.tex]

Re-judges every graded decision point twice -- with DMAIC_PQ_SCOPED=0 (trace-wide method set,
the pre-2026-09-18 rule) and =1 (wrong-turn evidence must post-date the fork's diagnostic) --
and counts the verdict transitions. Read-only; nothing under harbor/jobs is written.
"""
import argparse, json, os, sys
from collections import Counter
from pathlib import Path

sys.path[:0] = [".", "harbor/src"]
from dmaic_harbor import campaign_report as CR        # noqa: E402
import dmaic_harbor.verify as VF                       # noqa: E402
from dmaic_bench.core.models import trace_from_dict    # noqa: E402
from dmaic_bench.scoring import pq as PQ               # noqa: E402
from dmaic_bench import taxonomy as TX                 # noqa: E402

BASELINE = ["glm53flash-97-2026-09-12", "sonnet5-97", "gpt56sol-97", "gpt6astra-97", "glm-53-97",
            "gpt-56-luna-97", "deepseek-flash-97", "deepseek-v4-pro-97", "kimi-k3-97",
            "kimi-k3-97-fill", "claude-opus-5-97", "claude-opus-5-97-fill", "claude-fable-5-1-97"]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--tex"); ap.add_argument("--dataset", default="harbor/datasets/dmaic-bench-r3")
    a = ap.parse_args(); tx = TX.load(); ds = Path(a.dataset); C = Counter()
    for j in BASELINE:
        for r in CR._rows(Path("harbor/jobs") / j):
            if r["agent"] in ("oracle", "nop"):
                continue
            tp = Path("harbor/jobs") / j / r["trial"] / "artifacts" / "trace.json"
            tf = ds / r["trial"].rsplit("__", 1)[0] / "tests" / "stage" / "truth.json"
            if not tp.exists() or not tf.exists():
                C["skipped"] += 1; continue
            task = VF.build_task(VF.load_truth(str(tf))); trace = trace_from_dict(json.load(open(tp)))
            os.environ["DMAIC_PQ_SCOPED"] = "0"; old = PQ.score(task, trace, tx)
            os.environ["DMAIC_PQ_SCOPED"] = "1"; new = PQ.score(task, trace, tx)
            C["trials"] += 1
            for x, y in zip(old["details"], new["details"]):
                if x.get("kind") != "decision_point":
                    continue
                C["points"] += 1
                if (x["verdict"], x["via"]) != (y["verdict"], y["via"]):
                    C[("chg", x["verdict"], y["verdict"])] += 1
    changed = sum(v for k, v in C.items() if isinstance(k, tuple))
    to_correct = sum(v for k, v in C.items() if isinstance(k, tuple) and k[2] == "correct")
    print({str(k): v for k, v in C.items()})
    if a.tex:
        lines = ["% generated by scripts/pq_scoping_delta.py -- do not edit",
                 "\\newcommand{\\nCrossStage}{%d}" % changed,
                 "\\newcommand{\\nCrossStageToCorrect}{%d}" % to_correct,
                 "\\newcommand{\\nCrossStagePoints}{%d}" % C["points"]]
        Path(a.tex).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
