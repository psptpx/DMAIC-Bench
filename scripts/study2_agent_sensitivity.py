#!/usr/bin/env python3
"""Study 2 (expert audit): stratum table and sensitivity of the population-weighted
'acted on invalid evidence' rate (paper: 47% [31-61]) to the agent mix.

Reads only frozen inputs under paper/blind_review_2026-09-19/coordinator/. Writes nothing
into the repository; the LaTeX snippet goes next to this script.

Estimators (all over the 40 NO-GO units; acted = majority YES on forbidden conclusion OR
forbidden action, as in synthesize.py):
  design      sum(w_i * acted_i) / sum(w_i), w_i = population stratum / sample stratum
              (the paper's estimator)
  poststrat   design weights rescaled within agent so that each agent's total weight
              equals its number of reached NO-GO decisions in the 566-decision frame
  equalagent  unweighted mean over the 11 agents of each agent's unweighted acted rate
  equalagent_w  as equalagent but each agent's rate is design-weighted within agent
  unweighted  18/40
Bootstraps:
  case-clustered  resample the 12 sampled cases with replacement (study2_rescoring.py
                  method, seed 20260925, 4000 draws); a draw with no NO-GO unit is skipped
  stratified      resample units with replacement within each of the 8 design strata,
                  keeping stratum sizes and weights fixed (same seed and draw count)
  leave-one-agent-out  design estimate after dropping each agent's units
"""
import json, random, collections, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]  # repository root
CO = ROOT / "paper/blind_review_2026-09-19/coordinator"
HERE = pathlib.Path(__file__).resolve().parent
SEED, DRAWS = 20260925, 4000

MECH = {'M_msa':'measurement','M_agree':'measurement','M_agree1':'measurement','M_agree2':'measurement',
 'M_stability':'stability','M_pchart':'stability','M_chart_1':'stability','M_chart_2':'stability',
 'M_laney':'stability','M_chart_route':'stability',
 'A_anova':'cause','A_kruskal':'cause','A_factors':'cause','A_machine':'cause','A_variances':'cause','A_route':'cause',
 'A_screen':'experiment','A_rsm':'experiment','A_optimise':'experiment',
 'I_confirm':'confirmation','I_change':'confirmation','I_level':'confirmation'}
MORDER = ['stability', 'measurement', 'experiment', 'cause', 'confirmation']

res = json.loads((CO / "results_study2.json").read_text())
units = res["units"]
stop = [u for u in units if u["kind"] == "STOP"]
go = [u for u in units if u["kind"] == "GO"]
frame = json.loads((CO / "sampling_frame_decisions.json").read_text())
manifest = json.loads((CO / "manifest_sealed.json").read_text())

# ---------------------------------------------------------------- 1. stratum table
reached_stop = [d for d in frame if d["kind"] == "STOP" and d["verdict"] != "unknown"]
pop = collections.Counter((MECH[d["point"]], d["verdict"]) for d in reached_stop)
samp = collections.Counter((u["mech"], u["scorer"]) for u in stop)
print(f"frame: {len(frame)} decisions, {len(reached_stop)} reached NO-GO, "
      f"{len({d['model'] for d in frame})} agents")
assert sum(pop.values()) == 566
print("\nStratum table (mechanism x scorer verdict): population, sample, weight, unit weights in results")
print(f"{'mechanism':13s} {'verdict':9s} {'pop':>4s} {'n':>3s} {'pop/n':>8s} {'results weight':>15s} ok  acted")
rows = []
ok_all = True
for m in MORDER:
    for v in ("incorrect", "correct"):
        N, n = pop.get((m, v), 0), samp.get((m, v), 0)
        ws = sorted({round(u["weight"], 9) for u in stop if u["mech"] == m and u["scorer"] == v})
        acted = sum(u["acted"] for u in stop if u["mech"] == m and u["scorer"] == v)
        if N == 0 and n == 0:
            continue
        if n:
            w = N / n
            ok = len(ws) == 1 and abs(ws[0] - w) < 1e-9
            ok_all &= ok
            # manifest population_stop check
            ok &= manifest["population_stop"][f"{m}/{v}"] == N
            print(f"{m:13s} {v:9s} {N:4d} {n:3d} {w:8.3f} {str(ws):>15s} {'ok' if ok else 'MISMATCH'}  {acted}/{n}")
        else:
            print(f"{m:13s} {v:9s} {N:4d} {n:3d} {'--':>8s} {'--':>15s} (not sampled)  --")
        rows.append((m, v, N, n, acted))
print("all sampled-stratum weights equal population/sample:", ok_all)
W = sum(u["weight"] for u in stop)
print(f"sum of weights over 40 units = {W:.1f} (566 minus the 1 unsampled stability/correct decision = 565)")

def texrow(m, v, N, n, acted):
    w = f"{N/n:.2f}" if n else ""
    a = f"{acted}/{n}" if n else ""
    return f"{m} & {v} & {N} & {n} & {w} & {a} \\\\"
tex = [
 "% Study 2 sampling strata: population = reached NO-GO decisions in the 3,300-decision frame",
 "% (11 agents, first attempts); weight = population / sample. Generated by",
 "% scripts/study2_agent_sensitivity.py from coordinator/results_study2.json and",
 "% coordinator/sampling_frame_decisions.json.",
 "\\begin{table}[!ht]",
 "\\caption{\\textbf{Study~2 NO-GO strata.} Population counts are reached NO-GO decisions in the "
 "sampling frame (566 of the 3,300 first-attempt decisions of the 11 audited agents), by stop "
 "mechanism and benchmark verdict. Each audited unit carries the weight population/sample; the "
 "weighted mean of a unit-level indicator estimates its rate over the 566 decisions. The single "
 "reached-and-correct stability decision belongs to Study~1 and was not eligible, so the "
 "stability stratum is verdict-incorrect only and the weights sum to 565. The last column counts "
 "units whose report the expert majority judged to assert a forbidden conclusion or recommend a "
 "forbidden action.}",
 "\\label{tab:study2strata}",
 "\\centering\\small",
 "\\begin{tabular}{@{}llrrrr@{}}",
 "\\toprule",
 "Mechanism & Verdict & Population & Sample & Weight & Acted \\\\",
 "\\midrule"]
for m, v, N, n, acted in rows:
    tex.append(texrow(m, v, N, n, acted))
tex += ["\\midrule",
        f"Total & & {sum(r[2] for r in rows)} & {sum(r[3] for r in rows)} & & {sum(r[4] for r in rows)}/{len(stop)} \\\\",
        "\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
(HERE / "tab_study2strata.tex").write_text("\n".join(tex))
print("wrote", HERE / "tab_study2strata.tex")

# ---------------------------------------------------------------- 2. per-agent counts
agents = sorted({d["model"] for d in frame})
N_agent = collections.Counter(d["model"] for d in reached_stop)          # frame share
print("\nPer-agent: frame reached NO-GO (share), NO-GO units, acted, design-weight share, GO units")
print(f"{'agent':18s} {'frameNG':>7s} {'share':>6s} {'n':>3s} {'acted':>5s} {'wshare':>7s} {'GO n':>4s} {'GO acted':>8s}")
for a in sorted(agents, key=lambda a: -N_agent[a]):
    us = [u for u in stop if u["model"] == a]
    gs = [u for u in go if u["model"] == a]
    wsh = sum(u["weight"] for u in us) / W
    print(f"{a:18s} {N_agent[a]:7d} {N_agent[a]/566:6.3f} {len(us):3d} {sum(u['acted'] for u in us):5d} "
          f"{wsh:7.3f} {len(gs):4d} {sum(u['acted'] for u in gs):8d}")
print(f"agents with NO-GO units: {len({u['model'] for u in stop})}; with any unit: {len({u['model'] for u in units})}")

# ---------------------------------------------------------------- 3. estimators
def design(us):
    w = sum(u["weight"] for u in us)
    return sum(u["weight"] * u["acted"] for u in us) / w if w else None

def poststrat(us):
    # rescale design weights within agent so each present agent totals its frame count
    by = collections.defaultdict(list)
    for u in us: by[u["model"]].append(u)
    num = den = 0.0
    for a, xs in by.items():
        num += N_agent[a] * design(xs); den += N_agent[a]
    return num / den if den else None

def equalagent(us, weighted=False):
    by = collections.defaultdict(list)
    for u in us: by[u["model"]].append(u)
    vals = [design(xs) if weighted else sum(u["acted"] for u in xs) / len(xs) for xs in by.values()]
    return sum(vals) / len(vals) if vals else None

def unweighted(us):
    return sum(u["acted"] for u in us) / len(us) if us else None

EST = {"design (paper)": design, "poststrat by agent frame share": poststrat,
       "equal agent weights (unweighted within agent)": lambda us: equalagent(us, False),
       "equal agent weights (design-weighted within agent)": lambda us: equalagent(us, True),
       "unweighted 40": unweighted}

def ci(xs):
    xs = sorted(xs)
    return xs[int(0.025 * len(xs))], xs[int(0.975 * len(xs)) - 1]

# case-clustered bootstrap, study2_rescoring.py method (cases from all 60 units, skip if no NO-GO)
cases = sorted({u["case"] for u in units})
by_case = {c: [u for u in units if u["case"] == c] for c in cases}
def case_boot(seed):
    rng = random.Random(seed)
    out = {k: [] for k in EST}
    for _ in range(DRAWS):
        samp = [u for c in rng.choices(cases, k=len(cases)) for u in by_case[c]]
        s = [u for u in samp if u["kind"] == "STOP"]
        g = [u for u in samp if u["kind"] == "GO"]
        if not s or not g:
            continue
        for k, f in EST.items():
            out[k].append(f(s))
    return out

# stratified (within-stratum) bootstrap
strata = collections.defaultdict(list)
for u in stop: strata[(u["mech"], u["scorer"])].append(u)
def strat_boot(seed):
    rng = random.Random(seed)
    out = {k: [] for k in EST}
    for _ in range(DRAWS):
        s = [u for xs in strata.values() for u in rng.choices(xs, k=len(xs))]
        for k, f in EST.items():
            out[k].append(f(s))
    return out

cb = case_boot(SEED)
sb = strat_boot(SEED)
print(f"\nEstimates of the NO-GO 'acted on invalid evidence' rate (40 units, 18 acted)")
print(f"{'estimator':52s} {'point':>6s}  {'case-clustered 95%':>20s}  {'stratified 95%':>16s}")
for k, f in EST.items():
    p = f(stop); lo, hi = ci(cb[k]); slo, shi = ci(sb[k])
    print(f"{k:52s} {p*100:5.1f}%  [{lo*100:4.1f}, {hi*100:4.1f}] ({len(cb[k])} draws)  [{slo*100:4.1f}, {shi*100:4.1f}]")

# reproduce the paper's interval with the synthesize.py seed (20260919, NO-GO-only case list)
def synth_boot(seed=20260919):
    rng = random.Random(seed); cs = sorted({u["case"] for u in stop}); vals = []
    for _ in range(DRAWS):
        draw = rng.choices(cs, k=len(cs))
        sample = [u for c in draw for u in stop if u["case"] == c]
        v = design(sample)
        if v is not None: vals.append(v)
    return ci(vals)
lo, hi = synth_boot()
print(f"\ncheck: synthesize.py method (seed 20260919, NO-GO case list) design CI = [{lo*100:.1f}, {hi*100:.1f}]; "
      f"results_study2.json says {res['stop_all_40']['acted_on_invalid_evidence']}")

# leave-one-agent-out
print("\nLeave-one-agent-out (design estimator):")
for a in sorted(agents, key=lambda a: -N_agent[a]):
    us = [u for u in stop if u["model"] != a]
    if len(us) == len(stop): continue
    print(f"  drop {a:18s} -> {design(us)*100:5.1f}%  (n={len(us)})")

# by-mechanism acted rates (design-weighted = unweighted within mech/verdict, since weights are constant per stratum)
print("\nPer-mechanism design-weighted acted rate:")
for m in MORDER:
    us = [u for u in stop if u["mech"] == m]
    print(f"  {m:13s} {design(us)*100:5.1f}%  ({sum(u['acted'] for u in us)}/{len(us)})")
